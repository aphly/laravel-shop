            <div class="step-describe">
                <div class="step-title">
                    Step 1: Use the tape measure or a strip of paper to measure your
                    wrist.
                </div>
                <div class="step-content">
                    Just wrap the soft tape measure around the broadest part of your
                    wrist and take note of the length. If you are using a plain strip
                    of paper, mark your size with a pen or pencil then use a ruler to
                    measure the length (The starting end of the paper must be at the
                    base of the ruler and marked 0). That would be your wrist size.
                </div>
            </div>
        </div>
        <div class="items">
            <div class="media">
                <img alt="" src="/aphly/img/bracelet-size-2.png">
            </div>
