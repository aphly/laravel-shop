                    <p>
                        2. Wrap the piece of paper around your knuckle, which is the largest
                        point the ring will have to be able to get over.
                    </p>
                    <p>
                        3. Mark where the two ends of the paper first overlap with a marker.
                    </p>
                    <p>4. Measure the length with a ruler.</p>
