                <div class="step-title">
                    Step 2: Add one inch, or 2.5 centimeters, onto this measurement to
                    get the final length of your bracelets.
                </div>
                <div class="step-content">
                    Please make sure there's enough space to tuck in 2 fingers as this
                    is the space you need to add the charms. If you want to add less
                    than seven charms, add 2 centimeters are ok. If you plan to wear
                    eight or more charms, please add 3 centimeters. If you purchase a
                    bangle, just choose the next size from your actual wrist
                    measurement.
                </div>
            </div>
        </div>
    </div>
